def _duck_core(db: str, semantic_dir: str, runs_dir: Path):
    import duckdb

    from dataengineer.tools.func_tool.join_path_tools import JoinGraphBuilder, solve
    from dataengineer.tools.model_tools.tools import ModelingCore

    con = duckdb.connect(db, read_only=True)
    query = lambda sql: con.execute(sql).df()  # noqa: E731
    graph = JoinGraphBuilder(lambda sql: con.execute(sql).fetchall(), "duckdb", Path(semantic_dir)).build() \
        if semantic_dir else None
    return ModelingCore(runs_dir, query=query, semantic_dir=semantic_dir or None,
                        join_solver=(lambda tables: solve(graph, tables)) if graph else None)


def replay(core, recipe: Dict, run_id: str) -> Dict:
    """Re-run every recorded step with the same decisions and refit the chosen model."""
    res = core.define_task(run_id, recipe["spec"], recipe["source"])
    if not res["ok"]:
        raise RuntimeError(f"define_task failed: {res['errors']}")
    if recipe["clean_rules"]:
        core.clean_data(run_id, recipe["clean_rules"])
    if recipe["feature_templates"]:
        core.build_features(run_id, recipe["feature_templates"])
    sp = recipe["split"]
    core.make_split(run_id, sp.get("method", "random"), sp.get("test_size", 0.2), sp.get("n_folds", 5))
    return core.evaluate(run_id, model=recipe["model"], excluded=recipe["excluded_features"])


def replay_main(recipe_path: str, db: str, semantic_dir: str, out: str) -> None:
    recipe = json.loads(Path(recipe_path).read_text())
    core = _duck_core(db, semantic_dir, Path(out).parent.resolve())
    rep = replay(core, recipe, Path(out).name)
    print(json.dumps({"test": rep["test"], "baseline": rep["baseline"]}, indent=2))


def scoring_frame(recipe: Dict, core, input_df: Optional[pd.DataFrame], cutoff: Optional[str]) -> pd.DataFrame:
    from dataengineer.tools.model_tools import clean as clean_mod
    from dataengineer.tools.model_tools import features as feat_mod
    from dataengineer.tools.model_tools.pit import WindowAgg, window_sql

    spec = TaskSpec(**recipe["spec"])
    src = recipe["source"]
    if "label" in src:
        if not cutoff:
            raise ValueError("point-in-time model: pass --cutoff")
        pop = WindowAgg(name="_activity", **src["population"])
        sql = window_sql(pop, core.catalog(), core.join_solver, f"TIMESTAMP '{pd.Timestamp(cutoff)}'", side="feature")
        df = core.query(sql["sql"])[["entity_id"]].dropna()
        df["entity_id"] = df["entity_id"].astype(str)
        df = df.rename(columns={"entity_id": spec.entity})
        df["snapshot"] = str(pd.Timestamp(cutoff).date())
        spec.cutoffs = [df["snapshot"].iloc[0]] if len(df) else []
    else:
        if input_df is None:
            raise ValueError("pass --input with the rows to score")
        df = input_df.copy()
    rules = [r for r in recipe["clean_rules"]
             if r.get("column") != spec.target and spec.target not in (r.get("columns") or [])]
    if rules:
        df, _ = clean_mod.apply_rules(df, rules, protected=[c for c in (spec.entity, spec.time_col) if c])
    needs_pit = any(t.get("template") in ("pit_window", "sql_feature") for t in recipe["feature_templates"])
    out, _, _ = feat_mod.build_features(df, spec, recipe["feature_templates"], query=core.query,
                                        catalog=core.catalog() if needs_pit else None, join_solver=core.join_solver)
    return out


def score_main(recipe_path: str, model_path: str, input_path: Optional[str], cutoff: Optional[str], db: str,
               semantic_dir: str, out: str) -> None:
    import joblib

    recipe = json.loads(Path(recipe_path).read_text())
    fitted = joblib.load(model_path)
    core = _duck_core(db, semantic_dir, Path(out).resolve().parent / "_score_runs")
    df = None
    if input_path:
        df = pd.read_parquet(input_path) if input_path.endswith(".parquet") else pd.read_csv(input_path)
    frame = scoring_frame(recipe, core, df, cutoff)
    pred = fitted.predict(frame)
    keys = [c for c in (fitted.spec.entity, fitted.spec.time_col, "snapshot") if c and c in frame.columns]
    res = frame[keys].copy()
    res["prediction"] = pred if np.ndim(pred) == 1 else np.asarray(pred).argmax(1)
    res.to_csv(out, index=False)
    print(f"wrote {len(res)} predictions to {out}")
