"""export_artifacts (step 8): model card, recipe and reproducible train.py / score.py.

The recipe is the run's decision log reduced to what is needed to rebuild the model: the TaskSpec and data
source, cleaning rules, feature templates, split method and the chosen model with its parameters. train.py
replays it end to end against a database (same steps, same code); score.py applies the saved model to new
rows (or, for point-in-time tasks, to the population at a new cutoff).

The model card is filled from the run's own files (spec, selection, evaluation, leakage report, explanation);
only the limitations and usage notes are written by the LLM.
"""

import json
from pathlib import Path
from typing import Callable, Dict, List, Optional

import numpy as np
import pandas as pd

from dataengineer.tools.model_tools.spec import TaskSpec

TRAIN_PY = '''"""Rebuild the model from recipe.json (generated by gen_model)."""
import argparse, sys
sys.path.insert(0, {repo!r})
from dataengineer.tools.model_tools.export import replay_main

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default={db!r}, help="DuckDB file with the source tables")
    ap.add_argument("--semantic-dir", default={sem!r})
    ap.add_argument("--out", default="replay_run")
    a = ap.parse_args()
    replay_main({recipe!r}, a.db, a.semantic_dir, a.out)
'''

SCORE_PY = '''"""Score new data with the exported model (generated by gen_model).

Table/time-series tasks: --input <csv|parquet> with the same raw columns as the modeling table (time series:
include enough history for the lag features). Point-in-time tasks: --cutoff YYYY-MM-DD scores the population
active before that date, read from --db.
"""
import argparse, sys
sys.path.insert(0, {repo!r})
from dataengineer.tools.model_tools.export import score_main

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--input")
    ap.add_argument("--cutoff")
    ap.add_argument("--db", default={db!r})
    ap.add_argument("--semantic-dir", default={sem!r})
    ap.add_argument("--out", default="predictions.csv")
    a = ap.parse_args()
    score_main({recipe!r}, {model!r}, a.input, a.cutoff, a.db, a.semantic_dir, a.out)
'''


def build_recipe(decisions: List[Dict], selection: Dict, model: Optional[Dict] = None) -> Dict:
    last = {}
    for d in decisions:
        last[d["step"]] = d.get("decision") or {}
    if "define_task" not in last:
        raise ValueError("run has no define_task decision")
    return {
        "spec": last["define_task"]["spec"],
        "source": last["define_task"]["source"],
        "clean_rules": last.get("clean_data", {}).get("rules", []),
        "feature_templates": last.get("build_features", {}).get("templates", []),
        "split": last.get("make_split", {}),
        "excluded_features": selection.get("excluded", []),
        "model": model or selection["chosen"],
    }


def model_card(spec: TaskSpec, recipe: Dict, selection: Dict, evaluation: Dict, leakage: Optional[Dict],
               explanation: Optional[Dict], limitations: str, usage: str) -> str:
    pm = spec.primary_metric
    lines = [f"# Model card: {spec.name}", "",
             "## Task",
             f"- Type: {spec.task_type}; target `{spec.target}`"
             + (f" (positive = {spec.positive_label})" if spec.positive_label else ""),
             f"- Entity: {spec.entity or '-'}; time column: {spec.time_col or '-'}; "
             f"horizon: {spec.horizon or '-'}; cutoffs: {', '.join(spec.cutoffs) or spec.cutoff or '-'}",
             f"- Primary metric: {pm}; baseline: {spec.baseline}",
             "", "## Data and features",
             f"- Cleaning rules: {len(recipe['clean_rules'])}; feature templates: {len(recipe['feature_templates'])}",
             f"- Model inputs: {', '.join(selection['features']['numeric'] + selection['features']['categorical'] + selection.get('target_encoded', []))}",
             f"- Excluded by decision: {', '.join(recipe['excluded_features']) or '-'}"]
    if leakage:
        lines.append(f"- Leakage check: leak {leakage.get('leaky_features', [])}, "
                     f"suspect {leakage.get('suspect_features', [])}")
    lines += ["", "## Validation",
              f"- Split: {recipe['split'].get('method', '-')} (test share {recipe['split'].get('test_size', '-')}, "
              f"{recipe['split'].get('n_folds', '-')} folds)",
              "", "| candidate | CV " + pm + " | std | stage |", "|---|---|---|---|"]
    for r in selection["table"]:
        cv = "-" if r["cv_primary"] is None else f"{r['cv_primary']:.4f}"
        lines.append(f"| {r['label']} | {cv} | {r['cv_std']:.4f} | {r['stage']} |")
    lines += ["", f"- Chosen: **{selection['chosen']['label']}** — {selection['reason']}"]
    t = evaluation["test"]
    b = evaluation["baseline"]
    lines += ["", "## Test results (held out, scored once)",
              "| metric | model | baseline |", "|---|---|---|"]
    for k, v in t.items():
        bv = b.get(k)
        lines.append(f"| {k} | {'-' if v is None else f'{v:.4f}'} | {'-' if bv is None else f'{bv:.4f}'} |")
    if evaluation.get("calibration"):
        lines.append(f"- Calibration: Brier {evaluation['calibration']['brier']:.4f}, "
                     f"ECE {evaluation['calibration']['ece']:.4f}")
    if evaluation.get("findings"):
        lines += [f"- {f['check']}: {f['evidence']}" for f in evaluation["findings"]]
    if evaluation.get("drift_warning"):
        lines.append(f"- Drift (PSI > 0.2) between train and test: {', '.join(evaluation['drift_warning'])}")
    if explanation and explanation.get("global_importance"):
        lines += ["", f"## Explanation ({explanation['method']})"]
        lines += [f"- {g['feature']}: {g['mean_abs_contribution']:.4g}" for g in explanation["global_importance"][:10]]
    lines += ["", "## Limitations", limitations.strip() or "-", "", "## Intended use", usage.strip() or "-",
              "", "## Reproduce", "- `python train.py` rebuilds the model from recipe.json; "
              "`python score.py --input new.csv` (or `--cutoff`) scores new data."]
    return "\n".join(lines) + "\n"


def write_scripts(out: Path, repo: Path, db: str, semantic_dir: Optional[str]) -> List[str]:
    if db and Path(db).exists():
        db = str(Path(db).resolve())
    kw = {"repo": str(repo), "db": db, "sem": semantic_dir or "", "recipe": str(out / "recipe.json"),
          "model": str(out / "model.joblib")}
    (out / "train.py").write_text(TRAIN_PY.format(**kw))
    (out / "score.py").write_text(SCORE_PY.format(**kw))
    return [str(out / "train.py"), str(out / "score.py")]


