"""build_features: the LLM picks templates, code computes them point-in-time.

Templates
- row-wise (safe, no fitted statistics): date_parts, log1p, arith
- time series (per entity, sorted by time): lag, rolling. Every shift is forced to at least the gap
  between the forecast origin and the target (spec.horizon, or 1), so a feature can never read the
  value it predicts or anything later. Requested lags below the gap are raised and reported.
- point-in-time over event tables: pit_window (semantic measure aggregated over a window before the
  cutoff, SQL generated by pit.window_sql); sql_feature (a feature-catalog SQL with a {cutoff} placeholder,
  run once per cutoff; its time filter is checked by leakage_check, not trusted)
- fitted: target_encoding is recorded as deferred; it is fitted out-of-fold inside training, never on the
  full table (oof_target_encode below is the implementation training uses).

Every output column gets a meta record (template, sources, shift, window, sql) that leakage_check reads.
"""

from typing import Callable, Dict, List, Optional, Tuple

import numpy as np
import pandas as pd

from dataengineer.tools.model_tools.pit import SemanticCatalog, WindowAgg, window_sql
from dataengineer.tools.model_tools.spec import TaskSpec

DATE_PARTS = {
    "year": lambda t: t.dt.year,
    "month": lambda t: t.dt.month,
    "day": lambda t: t.dt.day,
    "dayofweek": lambda t: t.dt.dayofweek,
    "dayofyear": lambda t: t.dt.dayofyear,
    "weekofyear": lambda t: t.dt.isocalendar().week.astype(int),
    "hour": lambda t: t.dt.hour,
    "is_weekend": lambda t: (t.dt.dayofweek >= 5).astype(int),
    "quarter": lambda t: t.dt.quarter,
}
ARITH = {"+": np.add, "-": np.subtract, "*": np.multiply, "/": lambda a, b: np.divide(a, b.replace(0, np.nan))}
ROLL_STATS = ("mean", "std", "min", "max", "sum")
TEMPLATES = ("date_parts", "log1p", "arith", "lag", "rolling", "pit_window", "sql_feature", "target_encoding",
             "exclude")


class FeatureError(ValueError):
    pass


def _series_sorted(df: pd.DataFrame, spec: TaskSpec) -> pd.DataFrame:
    if not spec.time_col:
        raise FeatureError("lag/rolling need spec.time_col")
    keys = [c for c in (spec.entity, spec.time_col) if c]
    return df.sort_values(keys)


def _grouped(df: pd.DataFrame, spec: TaskSpec, col: str):
    return df.groupby(spec.entity, sort=False)[col] if spec.entity else df[col]


def build_features(
    df: pd.DataFrame,
    spec: TaskSpec,
    templates: List[Dict],
    query: Optional[Callable[[str], pd.DataFrame]] = None,
    catalog: Optional[SemanticCatalog] = None,
    join_solver: Optional[Callable[[List[str]], Dict]] = None,
) -> Tuple[pd.DataFrame, List[Dict], List[str]]:
    """Returns (feature table, meta per generated column, warnings). Input row order is preserved."""
    out = df.copy()
    out["__row"] = np.arange(len(out))
    meta: List[Dict] = []
    warnings: List[str] = []
    gap = max(1, int(spec.horizon or 1)) if spec.task_type == "timeseries" else 1
    excluded = set(spec.drop_columns)
    given = set(df.columns)

    def fresh(name: str) -> str:
        # never overwrite an input column (it may be a catalog feature the LLM chose to exclude)
        return f"{name}_gen" if name in given else name

    for tpl in templates:
        kind = tpl.get("template")
        if kind not in TEMPLATES:
            raise FeatureError(f"unknown template {kind!r}; allowed: {TEMPLATES}")
        if kind == "exclude":
            excluded |= set(tpl.get("columns", []))
        elif kind == "date_parts":
            col = tpl.get("column") or spec.time_col
            if col not in out.columns:
                raise FeatureError(f"date_parts column {col!r} not found")
            t = pd.to_datetime(out[col], errors="coerce")
            for p in tpl.get("parts", ["month", "dayofweek"]):
                if p not in DATE_PARTS:
                    raise FeatureError(f"unknown date part {p!r}; allowed {list(DATE_PARTS)}")
                name = f"{col}_{p}"
                out[name] = DATE_PARTS[p](t)
                meta.append({"name": name, "template": kind, "sources": [col], "uses_target": False})
        elif kind == "log1p":
            col = tpl["column"]
            if col == spec.target:
                raise FeatureError("log1p on the target is a target transform, not a feature")
            name = tpl.get("name", f"log1p_{col}")
            out[name] = np.log1p(out[col].clip(lower=0))
            meta.append({"name": name, "template": kind, "sources": [col], "uses_target": False})
        elif kind == "arith":
            left, right, op = tpl["left"], tpl["right"], tpl.get("op", "/")
            for side in (left, right):
                if not isinstance(side, (int, float)) and side not in out.columns:
                    raise FeatureError(f"arith operand {side!r} is neither a column nor a number")
            if spec.target in (left, right):
                raise FeatureError("arith may not use the target column; use lag/rolling for past target values")
            if op not in ARITH:
                raise FeatureError(f"op must be one of {list(ARITH)}")
            name = tpl.get("name", f"{left}{op}{right}")
            lv = out[left].astype(float) if not isinstance(left, (int, float)) else pd.Series(float(left), index=out.index)
            rv = out[right].astype(float) if not isinstance(right, (int, float)) else pd.Series(float(right), index=out.index)
            out[name] = ARITH[op](lv, rv)
            meta.append({"name": name, "template": kind, "uses_target": False,
                         "sources": [c for c in (left, right) if not isinstance(c, (int, float))]})
        elif kind in ("lag", "rolling"):
            col = tpl.get("column", spec.target)
            out = _series_sorted(out, spec)
            if kind == "lag":
                for k in tpl.get("lags", [1]):
                    k_eff = max(int(k), gap)
                    if k_eff != int(k):
                        warnings.append(f"lag {k} of {col} raised to {k_eff}: values closer than the horizon "
                                        f"({gap}) are unknown at forecast time")
                    name = fresh(f"{col}_lag{k_eff}")
                    out[name] = _grouped(out, spec, col).shift(k_eff)
                    meta.append({"name": name, "template": kind, "sources": [col], "uses_target": col == spec.target,
                                 "shift": k_eff})
            else:
                shift = max(int(tpl.get("shift", gap)), gap)
                for w in tpl.get("windows", [7]):
                    for stat in tpl.get("stats", ["mean"]):
                        if stat not in ROLL_STATS:
                            raise FeatureError(f"rolling stat must be one of {ROLL_STATS}")
                        name = fresh(f"{col}_roll{w}_{stat}_s{shift}")
                        shifted = _grouped(out, spec, col).shift(shift)
                        grp = shifted.groupby(out[spec.entity], sort=False) if spec.entity else shifted
                        out[name] = grp.transform(lambda s: getattr(s.rolling(int(w), min_periods=1), stat)())
                        meta.append({"name": name, "template": kind, "sources": [col],
                                     "uses_target": col == spec.target, "shift": shift, "window": int(w)})
        elif kind == "pit_window":
            if query is None or catalog is None:
                raise FeatureError("pit_window needs a database and a semantic catalog")
            out, m = _pit_window(out, spec, tpl, query, catalog, join_solver)
            meta.extend(m)
        elif kind == "sql_feature":
            if query is None:
                raise FeatureError("sql_feature needs a database")
            out, m = _sql_feature(out, spec, tpl, query, catalog)
            meta.append(m)
        elif kind == "target_encoding":
            col = tpl["column"]
            if col not in out.columns:
                raise FeatureError(f"target_encoding column {col!r} not found")
            meta.append({"name": f"te_{col}", "template": kind, "sources": [col], "uses_target": True,
                         "deferred": True, "folds": int(tpl.get("folds", 5)), "smoothing": float(tpl.get("smoothing", 20))})

    out = out.sort_values("__row").drop(columns="__row").reset_index(drop=True)
    drop = [c for c in excluded if c in out.columns and c not in (spec.target, spec.entity, spec.time_col, "snapshot", "__rid")]
    out = out.drop(columns=drop)
    if drop:
        meta.append({"name": None, "template": "exclude", "sources": drop})
    return out, meta, warnings


def _pit_window(out, spec, tpl, query, catalog, join_solver):
    if "snapshot" not in out.columns and not spec.cutoff:
        raise FeatureError("pit_window needs spec.cutoff or a snapshot column (one row per entity per cutoff)")
    if not spec.entity:
        raise FeatureError("pit_window needs spec.entity")
    meta = []
    cutoffs = sorted(out["snapshot"].astype(str).unique()) if "snapshot" in out.columns else [spec.cutoff]
    for w in tpl.get("windows", [90]):
        name = tpl.get("name", f"{tpl['measure']}_{w}d")
        if len(tpl.get("windows", [90])) > 1:
            name = f"{tpl.get('name', tpl['measure'])}_{w}d"
        agg = WindowAgg(name=name, measure=tpl["measure"], window_days=int(w), entity=tpl.get("entity_ref", "customer"),
                        time_dim=tpl.get("time_dim", "invoice_date"), filters=tpl.get("filters"))
        parts = []
        sql_first = None
        for c in cutoffs:
            r = window_sql(agg, catalog, join_solver, f"TIMESTAMP '{pd.Timestamp(c)}'", side="feature")
            sql_first = sql_first or r
            res = query(r["sql"])
            res["snapshot"] = c
            parts.append(res)
        vals = pd.concat(parts, ignore_index=True) if parts else pd.DataFrame(columns=["entity_id", name, "snapshot"])
        key = out[spec.entity].astype(str)
        snap = out["snapshot"].astype(str) if "snapshot" in out.columns else pd.Series(spec.cutoff, index=out.index)
        vals["entity_id"] = vals["entity_id"].astype(str)
        mapping = vals.set_index(["entity_id", "snapshot"])[name]
        idx = pd.MultiIndex.from_arrays([key, snap])
        out[name] = mapping.reindex(idx).to_numpy()
        fill = tpl.get("fill", 0)
        if fill is not None:
            out[name] = out[name].fillna(fill)
        meta.append({"name": name, "template": "pit_window", "sources": [tpl["measure"]], "uses_target": False,
                     "window": sql_first["window"], "sql": sql_first["sql"], "time_expr": sql_first["time_expr"],
                     "join_plan": sql_first["join_plan"]})
    return out, meta


def _snapshot_keys(out: pd.DataFrame, spec: TaskSpec):
    if not spec.entity:
        raise FeatureError("point-in-time features need spec.entity")
    if "snapshot" not in out.columns and not spec.cutoff:
        raise FeatureError("point-in-time features need spec.cutoff or a snapshot column")
    cutoffs = sorted(out["snapshot"].astype(str).unique()) if "snapshot" in out.columns else [spec.cutoff]
    key = out[spec.entity].astype(str)
    snap = out["snapshot"].astype(str) if "snapshot" in out.columns else pd.Series(spec.cutoff, index=out.index)
    return cutoffs, pd.MultiIndex.from_arrays([key, snap])


def _sql_feature(out, spec, tpl, query, catalog):
    name, sql = tpl["name"], tpl["sql"]
    cutoffs, idx = _snapshot_keys(out, spec)
    parts = []
    for c in cutoffs:
        res = query(sql.replace("{cutoff}", str(pd.Timestamp(c))))
        if "entity_id" not in res.columns or name not in res.columns:
            raise FeatureError(f"sql_feature {name!r} must return columns entity_id and {name}")
        res = res[["entity_id", name]].copy()
        res["entity_id"] = res["entity_id"].astype(str)
        res["snapshot"] = c
        parts.append(res)
    vals = pd.concat(parts, ignore_index=True).drop_duplicates(["entity_id", "snapshot"])
    out[name] = vals.set_index(["entity_id", "snapshot"])[name].reindex(idx).to_numpy()
    if tpl.get("fill", 0) is not None:
        out[name] = out[name].fillna(tpl.get("fill", 0))
    time_col = tpl.get("time_column")
    if not time_col and catalog is not None:
        time_col = [o.expr for objs in catalog.objects.values() for o in objs if o.kind == "dimension" and o.type == "TIME"]
    meta = {"name": name, "template": "sql_feature", "sources": [], "uses_target": False,
            "sql": sql.replace("{cutoff}", str(pd.Timestamp(cutoffs[0]))), "cutoff": cutoffs[0], "time_column": time_col}
    if "{cutoff}" not in sql:
        meta["note"] = "no {cutoff} placeholder: the same values are used for every snapshot"
    return out, meta


def oof_target_encode(train_col: pd.Series, y: pd.Series, test_col: Optional[pd.Series] = None, folds: int = 5,
                      smoothing: float = 20.0, seed: int = 0) -> Tuple[pd.Series, Optional[pd.Series]]:
    """Out-of-fold mean target encoding: each training row is encoded from the other folds only, test rows
    from the whole training set. Smoothed towards the global mean by `smoothing` pseudo-rows."""
    rng = np.random.RandomState(seed)
    fold = rng.randint(0, folds, size=len(train_col))
    prior = float(y.mean())
    enc = pd.Series(np.nan, index=train_col.index)
    for k in range(folds):
        fit = fold != k
        stats = y[fit].groupby(train_col[fit]).agg(["sum", "count"])
        m = (stats["sum"] + prior * smoothing) / (stats["count"] + smoothing)
        enc[~fit] = train_col[~fit].map(m).fillna(prior).to_numpy()
    test_enc = None
    if test_col is not None:
        stats = y.groupby(train_col).agg(["sum", "count"])
        m = (stats["sum"] + prior * smoothing) / (stats["count"] + smoothing)
        test_enc = test_col.map(m).fillna(prior)
    return enc, test_enc
